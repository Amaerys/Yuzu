PX, ADV = 100, 600
names = {".notdef": None}
order = [".notdef"]
cmap = {}
glyphs = {}
def bounds(rows):
    cols = [x for row in rows for x, ch in enumerate(row) if ch == "#"]
    return (min(cols), max(cols)) if cols else (0, 2)
def draw(rows, shift=0):
    pen = TTGlyphPen(None)
    for r, row in enumerate(rows):
        assert len(row) == 5, (rows, row)
        top = (7 - r) * PX; bot = top - PX
        x = 0
        while x < 5:
            if row[x] == "#":
                x0 = x
                while x < 5 and row[x] == "#": x += 1
                a, b = (x0 - shift) * PX, (x - shift) * PX
                pen.moveTo((a, bot)); pen.lineTo((a, top)); pen.lineTo((b, top)); pen.lineTo((b, bot)); pen.closePath()
            else: x += 1
    return pen.glyph()
glyphs[".notdef"] = draw(["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"])
adv = {".notdef": ADV}
# Proportional: each glyph is trimmed to its inked columns plus one pixel of space. Digits stay 6 px wide so numbers line up.
for ch, rows in G.items():
    name = "uni%04X" % ord(ch)
    order.append(name); cmap[ord(ch)] = name
    if ch.isdigit(): glyphs[name] = draw(rows); adv[name] = ADV; continue
    if ch == " ": glyphs[name] = draw(rows); adv[name] = 4 * PX; continue
    l, r = bounds(rows); glyphs[name] = draw(rows, l); adv[name] = (r - l + 2) * PX
fb = FontBuilder(1000, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap(cmap)
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics({n: (adv[n], 0) for n in order})
fb.setupHorizontalHeader(ascent=800, descent=-200)
fb.setupNameTable({"familyName": "Yuzu Pixel", "styleName": "Regular"})
fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, sTypoLineGap=0, usWinAscent=800, usWinDescent=200, sxHeight=500, sCapHeight=700)
fb.setupPost()
fb.font.flavor = "woff"
out = os.path.join(os.path.dirname(__file__), "..", "..", "public", "fonts", "yuzu-pixel.woff")
os.makedirs(os.path.dirname(out), exist_ok=True)
fb.save(out)
print("glyphs", len(G), "bytes", os.path.getsize(out))
